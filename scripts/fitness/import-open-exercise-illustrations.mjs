#!/usr/bin/env node
// Re-runnable import of the pinned Open Exercise Illustrations catalogue (CC0).
//   node scripts/fitness/import-open-exercise-illustrations.mjs [--source <checkout dir>] [--check]
// Without --source the pinned commit is downloaded. --check writes nothing and fails when a run would change any output.
import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const REPOSITORY = 'hitmanrepo/open-exercise-illustrations';
const COMMIT = '2786aefa4b36a08faeca8114e0d1eb0af3ef6732';
const EXERCISES_SHA256 = 'ee79dc951c2b523c04e141c59b257b893cd7df4d492543aa1a1e8c46360c7f75';
const FRAMES = new Set(['start', 'mid', 'end', 'hold']);
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const pinnedDir = path.join(root, 'scripts/fitness/open-exercise-illustrations');
const assetDir = path.join(root, 'src/assets/fitness/exercises');
const rightsFile = path.join(root, 'src/assets/fitness/illustration-sources.json');
const catalogFile = path.join(root, 'src/app/core/models/exercise-catalog.generated.ts');
const args = process.argv.slice(2);
const check = args.includes('--check');
const sourceArg = args.includes('--source') ? args[args.indexOf('--source') + 1] : process.env.OEI_SOURCE_DIR;

function sourceDir() {
  if (sourceArg) return path.resolve(sourceArg);
  const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'oei-'));
  const tarball = path.join(tmp, 'source.tar.gz');
  execFileSync('curl', ['-sfL', '-o', tarball, 'https://codeload.github.com/' + REPOSITORY + '/tar.gz/' + COMMIT]);
  execFileSync('tar', ['xzf', tarball, '-C', tmp]);
  return path.join(tmp, 'open-exercise-illustrations-' + COMMIT);
}

const sha256 = (buffer) => createHash('sha256').update(buffer).digest('hex');
const source = sourceDir();
const exercisesJson = fs.readFileSync(path.join(source, 'exercises.json'));
if (sha256(exercisesJson) !== EXERCISES_SHA256) throw new Error('exercises.json does not match the pinned commit.');
const data = JSON.parse(exercisesJson);
const exercises = data.exercises;
const variants = data.variants ?? [];

const ids = exercises.map((exercise) => exercise.id);
if (new Set(ids).size !== ids.length) throw new Error('Source has duplicate exercise ids.');
const known = new Set(ids);
const outputs = new Map();
const images = {};
for (const exercise of exercises) {
  if (!/^[a-z0-9]+(-[a-z0-9]+)*$/.test(exercise.id)) throw new Error('Unexpected id shape: ' + exercise.id);
  if (!exercise.frames.length) throw new Error('Exercise has no frames: ' + exercise.id);
  for (const frame of exercise.frames) {
    if (!FRAMES.has(frame)) throw new Error('Unexpected frame: ' + exercise.id + '/' + frame);
    const relative = exercise.images[frame];
    if (relative !== 'images/' + exercise.id + '/' + frame + '.webp') throw new Error('Unexpected image path: ' + relative);
    const bytes = fs.readFileSync(path.join(source, relative));
    images[relative] = sha256(bytes);
    outputs.set(path.join(assetDir, exercise.id, frame + '.webp'), bytes);
  }
}
for (const variant of variants) {
  if (!known.has(variant.imageOf)) throw new Error('Variant points at unknown exercise: ' + variant.id);
  if (known.has(variant.id)) throw new Error('Variant id collides with an exercise id: ' + variant.id);
}

const entries = exercises.map((exercise) => ({
  id: exercise.id,
  name: exercise.name,
  aliases: exercise.aliases ?? [],
  variants: variants
    .filter((variant) => variant.imageOf === exercise.id)
    .map((variant) => ({ id: variant.id, name: variant.name, ...(variant.difference ? { difference: variant.difference } : {}) })),
  equipment: exercise.equipment ?? [],
  equipmentLabel: exercise.equipmentLabel ?? null,
  primaryMuscles: exercise.muscles.primary,
  secondaryMuscles: exercise.muscles.secondary,
  movementPattern: exercise.movementPattern,
  category: exercise.category,
  unilateral: exercise.unilateral,
  frames: exercise.frames,
  width: exercise.width,
  height: exercise.height,
}));
const text = (value) => Buffer.from(value, 'utf8');
const prettier = await import('prettier');
const formatted = async (file, value) =>
  text(await prettier.format(value, { ...(await prettier.resolveConfig(file)), filepath: file }));
outputs.set(
  catalogFile,
  await formatted(
    catalogFile,
    "// Generated by scripts/fitness/import-open-exercise-illustrations.mjs. Do not edit by hand.\n" +
      "import type { SourceCatalogEntry } from './exercise-catalog.types';\n\n" +
      'export const sourceCatalogPin = ' + JSON.stringify({ repository: REPOSITORY, commit: COMMIT, license: 'CC0-1.0' }) + ' as const;\n\n' +
      'export const sourceCatalogEntries: readonly SourceCatalogEntry[] = ' + JSON.stringify(entries, null, 1) + ';\n',
  ),
);
outputs.set(path.join(pinnedDir, 'exercises.json'), exercisesJson);
outputs.set(path.join(pinnedDir, 'LICENSE'), fs.readFileSync(path.join(source, 'LICENSE')));
outputs.set(
  path.join(pinnedDir, 'source.json'),
  text(JSON.stringify({ repository: REPOSITORY, commit: COMMIT, license: 'CC0-1.0', exercises: exercises.length, variants: variants.length, images }, null, 2) + '\n'),
);
outputs.set(
  rightsFile,
  text(
    JSON.stringify(
      {
        origin: 'Open Exercise Illustrations',
        repository: 'https://github.com/' + REPOSITORY,
        commit: COMMIT,
        sourceUrl: 'https://github.com/' + REPOSITORY + '/tree/' + COMMIT,
        license: 'CC0 1.0 Universal',
        licenseUrl: 'https://github.com/' + REPOSITORY + '/blob/' + COMMIT + '/LICENSE',
        changes: 'Không chỉnh sửa. Tệp images/<mã>/<khung>.webp của nguồn nằm tại assets/fitness/exercises/<mã>/<khung>.webp.',
        note: 'Hình do AI tạo. Tác giả ghi chưa có huấn luyện viên thẩm định. Kỹ thuật trong ứng dụng đối chiếu theo nguồn kỹ thuật riêng của từng bài.',
        exercises: exercises.length,
        files: Object.keys(images).length,
      },
      null,
      2,
    ) + '\n',
  ),
);

const expectedAssets = new Set([...outputs.keys()].filter((file) => file.startsWith(assetDir + path.sep)));
const stale = [];
if (fs.existsSync(assetDir)) {
  for (const dir of fs.readdirSync(assetDir, { withFileTypes: true })) {
    if (!dir.isDirectory()) {
      stale.push(path.join(assetDir, dir.name));
      continue;
    }
    for (const file of fs.readdirSync(path.join(assetDir, dir.name))) {
      const full = path.join(assetDir, dir.name, file);
      if (!expectedAssets.has(full)) stale.push(full);
    }
  }
}
const changed = [...outputs].filter(([file, bytes]) => !fs.existsSync(file) || !fs.readFileSync(file).equals(bytes)).map(([file]) => file);
if (check) {
  for (const file of [...changed, ...stale]) console.error('would change: ' + path.relative(root, file));
  console.log(exercises.length + ' exercises, ' + Object.keys(images).length + ' images, ' + changed.length + ' to write, ' + stale.length + ' stale');
  process.exit(changed.length || stale.length ? 1 : 0);
}
for (const file of stale) fs.rmSync(file);
for (const [file, bytes] of outputs) {
  if (!changed.includes(file)) continue;
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, bytes);
}
if (fs.existsSync(assetDir)) {
  for (const dir of fs.readdirSync(assetDir, { withFileTypes: true })) {
    if (dir.isDirectory() && !known.has(dir.name)) fs.rmSync(path.join(assetDir, dir.name), { recursive: true });
  }
}
console.log(exercises.length + ' exercises, ' + Object.keys(images).length + ' images, ' + changed.length + ' written, ' + stale.length + ' stale removed');
