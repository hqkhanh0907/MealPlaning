#!/usr/bin/env node
/**
 * Obfuscate Gemini API key from `.env` → `src/environments/environment.prod.ts`.
 *
 * Strategy: XOR with rotating key + base64. NOT encryption — only stops
 * casual `strings app.apk | grep AIzaSy` extraction. See
 * `docs/5-development/phase-1.5b-ai-foundation.md` §3.7 for security caveat.
 *
 * Run: `npm run obfuscate:key` (also auto-runs as `prebuild` hook).
 *
 * Inputs:
 *   - .env  (gitignored)            GEMINI_API_KEY=AIza...
 *
 * Outputs:
 *   - src/environments/environment.prod.ts  (gitignored, generated)
 *
 * Exit codes:
 *   0  success
 *   1  .env missing or GEMINI_API_KEY missing
 *   2  write failed
 */

import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const REPO_ROOT = resolve(__dirname, '..');

const OBF_KEY = 'HealthMate-2026';
const ENV_FILE = resolve(REPO_ROOT, '.env');
const OUT_FILE = resolve(REPO_ROOT, 'src/environments/environment.prod.ts');
const MODEL = 'gemini-2.5-flash';
const DB_NAME = 'healthmate.db';
const PKG = JSON.parse(readFileSync(resolve(REPO_ROOT, 'package.json'), 'utf8'));
const APP_VERSION = PKG.version;

function obfuscate(plain) {
  if (!plain) return '';
  const xored = Array.from(plain)
    .map((ch, i) =>
      String.fromCharCode(
        ch.charCodeAt(0) ^ OBF_KEY.charCodeAt(i % OBF_KEY.length),
      ),
    )
    .join('');
  return Buffer.from(xored, 'binary').toString('base64');
}

function readDotEnv(path) {
  const raw = readFileSync(path, 'utf8');
  const out = {};
  for (const line of raw.split('\n')) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith('#')) continue;
    const eq = trimmed.indexOf('=');
    if (eq < 0) continue;
    const key = trimmed.slice(0, eq).trim();
    const value = trimmed.slice(eq + 1).trim().replace(/^["']|["']$/g, '');
    out[key] = value;
  }
  return out;
}

function main() {
  if (!existsSync(ENV_FILE)) {
    console.error('✗ .env not found at', ENV_FILE);
    console.error('  Copy .env.example → .env and fill GEMINI_API_KEY.');
    process.exit(1);
  }
  const env = readDotEnv(ENV_FILE);
  const plain = env.GEMINI_API_KEY ?? '';
  if (!plain || plain === 'AIza-your-key-here') {
    console.error('✗ GEMINI_API_KEY missing or placeholder in .env');
    process.exit(1);
  }

  const obf = obfuscate(plain);
  const content = `/**
 * Production environment — GENERATED by scripts/obfuscate-gemini-key.mjs.
 *
 * DO NOT EDIT MANUALLY — changes will be overwritten on next build.
 * DO NOT COMMIT — file is gitignored.
 *
 * To regenerate: \`npm run obfuscate:key\`.
 */
export const environment = {
  production: true,
  appVersion: '${APP_VERSION}',
  geminiApiKeyObf: '${obf}',
  geminiModel: '${MODEL}',
  dbName: '${DB_NAME}',
};
`;

  try {
    writeFileSync(OUT_FILE, content, 'utf8');
  } catch (err) {
    console.error('✗ Failed to write', OUT_FILE, err.message);
    process.exit(2);
  }
  console.log(
    `✓ Obfuscated GEMINI_API_KEY (${plain.length} chars → ${obf.length} chars base64)`,
  );
  console.log(`✓ Wrote ${OUT_FILE}`);
}

main();
